#!/usr/bin/env node
// Build standalone, playable demo pages into artifacts/demos/ (open index.html in a browser).
// Pipeline per demo: source -> (importer) -> canonical validation -> renderer adapter -> the
// pinned WASM engine's own player page. Needs `npm run engine:build` and Node >= 22.18.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "artifacts", "demos");
mkdirSync(out, { recursive: true });

// Bundle the TypeScript pipeline once (esbuild), then import it.
const bundled = resolve(out, ".pipeline.mjs");
await build({
  stdin: {
    contents: `export { importDiagram } from "./packages/diagram-importers/src/index.ts";
export { toEngineDocument, serializeEngineDocument } from "./packages/renderer-adapter/src/index.ts";
export { fillPlayerTemplate } from "./packages/engine-host/src/template.ts";`,
    resolveDir: root,
    loader: "ts",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: bundled,
  logLevel: "silent",
});
const { importDiagram, toEngineDocument, serializeEngineDocument, fillPlayerTemplate } =
  await import(pathToFileURL(bundled).href);
const template = readFileSync(resolve(root, "build", "engine", "player-template.html"), "utf8");
mkdirSync(out, { recursive: true });

const demos = [
  {
    file: "order-flow.html",
    title: "Order flow: parallel consumers, failure, retry, response",
    note: "Hand-written canonical scenario (fixtures/scenarios/order-flow.canonical.json)",
    load: async () =>
      JSON.parse(
        readFileSync(resolve(root, "fixtures/scenarios/order-flow.canonical.json"), "utf8"),
      ),
  },
  {
    file: "linear-3.html",
    title: "Linear request/response",
    note: "fixtures/scenarios/linear-3.canonical.json",
    load: async () =>
      JSON.parse(readFileSync(resolve(root, "fixtures/scenarios/linear-3.canonical.json"), "utf8")),
  },
  {
    file: "mermaid-sequence.html",
    title: "Imported Mermaid sequence diagram (checkout)",
    note: "Imported from fixtures/diagrams/15-sequence-rich.mmd: messages, failed charge, retry, async event, parallel reply",
    source: "fixtures/diagrams/15-sequence-rich.mmd",
    format: "mermaid",
  },
  {
    file: "mermaid-simple-sequence.html",
    title: "Imported Mermaid sequence diagram (simple)",
    note: "Imported from fixtures/diagrams/11-sequence.mmd",
    source: "fixtures/diagrams/11-sequence.mmd",
    format: "mermaid",
  },
  {
    file: "drawio-order-flow-static.html",
    title: "Imported draw.io diagram (static, no scenario yet)",
    note: "Imported from fixtures/diagrams/10-order-flow.drawio. Static: generating the animation from a diagram is the next phase (P1.5).",
    source: "fixtures/diagrams/10-order-flow.drawio",
    format: "drawio",
  },
  {
    file: "mermaid-flowchart-static.html",
    title: "Imported Mermaid flowchart with subgraphs (static, groups flattened)",
    note: "Imported from fixtures/diagrams/14-mermaid-syntax.mmd; laid out by dagre. Static until P1.5.",
    source: "fixtures/diagrams/14-mermaid-syntax.mmd",
    format: "mermaid",
  },
];

const rows = [];
for (const d of demos) {
  let doc;
  if (d.load) doc = await d.load();
  else {
    const r = await importDiagram(readFileSync(resolve(root, d.source), "utf8"), d.format);
    if (!r.ok) throw new Error(`${d.source}: ${JSON.stringify(r.errors)}`);
    doc = r.document;
    if (!doc.scenario)
      doc = { ...doc, scenario: { id: "static", durationMs: 3000, flows: [], events: [] } };
  }
  const a = toEngineDocument(doc, { groups: "flatten" });
  if (!a.ok) throw new Error(`${d.file}: ${JSON.stringify(a.errors)}`);
  const html = fillPlayerTemplate(template, serializeEngineDocument(a.document), d.title, {
    autoplay: true,
    loop: true,
  });
  writeFileSync(resolve(out, d.file), html);
  rows.push(`<li><a href="${d.file}">${d.title}</a><br><small>${d.note}</small></li>`);
  console.log(`[demos] ${d.file}`);
}
writeFileSync(
  resolve(out, "index.html"),
  `<!doctype html><meta charset="utf-8"><title>ArchFlow demos</title>
<style>body{font:15px system-ui,sans-serif;max-width:760px;margin:40px auto;padding:0 16px;line-height:1.5}li{margin:14px 0}small{color:#666}</style>
<h1>ArchFlow AI demos</h1>
<p>Each page is the pinned AnimatedDiagrams WASM engine's player, fed by ArchFlow's validator and renderer adapter. Open a page; it autoplays and loops. Generated by <code>node scripts/make-demos.mjs</code>.</p>
<ul>${rows.join("\n")}</ul>`,
);
console.log(`[demos] open ${resolve(out, "index.html")}`);
